// Admin system screens: backups, update + rollback, start with Windows (inside الإعدادات),
// and the مشاركة page (tunnel link + QR codes).
import { h, toast, confirmModal, fill } from './ui.js';
import { get, post, put } from './api.js';

const fmtTime = (iso) => (iso ? new Date(iso.includes('T') ? iso : iso.replace(' ', 'T')).toLocaleString('ar-EG') : '—');
const fmtSize = (n) => (n > 1048576 ? `${(n / 1048576).toFixed(1)} م.ب` : `${Math.max(1, Math.round(n / 1024))} ك.ب`);
const svg = (markup) => {
  const box = h('div', { class: 'qr' });
  box.innerHTML = markup; // generated by the server's QR library, not user text
  return box;
};

// ---------- backups ----------
export async function backupsCard() {
  const card = h('div', { class: 'card grid' });
  async function load() {
    const { backups, status } = await get('/api/backups');
    const warn = [];
    if (status.error) warn.push(`آخر نسخة احتياطية فشلت: ${status.error}`);
    if (status.copy_error) warn.push(`النسخة اتعملت بس متنسختش على الفولدر التاني: ${status.copy_error}`);
    if (status.stale && !status.error) warn.push('مفيش نسخة احتياطية من أكتر من يومين.');
    const dirInput = h('input', { value: status.copy_dir || '', placeholder: 'مثال: E:\\ أو C:\\Users\\...\\OneDrive', style: 'flex:1;min-width:200px' });
    fill(card,
      h('h2', {}, 'النسخ الاحتياطي'),
      h('div', { class: 'small muted' }, 'بيتعمل نسخة لوحده كل ما البرنامج يشتغل، وكل يوم، وقبل أي تحديث.'),
      h('div', {}, 'آخر نسخة: ', h('b', {}, fmtTime(status.last_at))),
      warn.map((w) => h('div', { class: 'issue red' }, w)),
      h('div', { class: 'row' },
        h('button', { class: 'btn primary', onclick: async (e) => {
          e.target.disabled = true;
          try { await post('/api/backups'); toast('اتعملت نسخة احتياطية ✓'); await load(); } catch (ex) { toast(ex.message, true); e.target.disabled = false; }
        } }, 'اعمل نسخة دلوقتي')),
      h('div', { class: 'field' }, h('label', {}, 'انسخ كل نسخة كمان على فلاشة أو فولدر OneDrive (اختياري)'),
        h('div', { class: 'row' }, dirInput, h('button', { class: 'btn', onclick: async () => {
          try { await put('/api/backups/settings', { backup_copy_dir: dirInput.value }); toast('اتحفظ'); await load(); } catch (ex) { toast(ex.message, true); }
        } }, 'حفظ'))),
      backups.length === 0 ? h('div', { class: 'muted' }, 'لسه مفيش نسخ.') : h('div', { class: 'table-wrap', style: 'max-height:320px;overflow:auto' }, h('table', {},
        h('thead', {}, h('tr', {}, ['الوقت', 'النوع', 'الحجم', ''].map((t) => h('th', {}, t)))),
        h('tbody', {}, backups.map((b) => h('tr', {},
          h('td', { class: 'num' }, fmtTime(b.at)),
          h('td', {}, b.reason_name),
          h('td', { class: 'num' }, fmtSize(b.size)),
          h('td', { class: 'row', style: 'justify-content:flex-end' },
            h('a', { class: 'btn sm', href: `/api/backups/${encodeURIComponent(b.name)}/download` }, 'تحميل'),
            h('button', { class: 'btn sm danger', onclick: () => restore(b) }, 'استرجاع'))))))),
    );
  }
  async function restore(b) {
    const ok = await confirmModal('استرجاع نسخة احتياطية',
      `البيانات هترجع زي ما كانت وقت ${fmtTime(b.at)}. أي حاجة اتسجلت بعد كده هتختفي من البرنامج (بس هتتحفظ في نسخة احتياطية قبل الاسترجاع). متأكد؟`, 'استرجع');
    if (!ok) return;
    try {
      await post(`/api/backups/${encodeURIComponent(b.name)}/restore`, { confirm: true });
      toast('البيانات اترجعت ✓');
      setTimeout(() => location.reload(), 800);
    } catch (ex) { toast(ex.message, true); }
  }
  await load();
  return card;
}

// ---------- update + rollback ----------
export async function updateCard() {
  const card = h('div', { class: 'card grid' });
  function render(s) {
    const cur = s.current.build ? `${s.current.version} (رقم ${s.current.build})` : `${s.current.version} (نسخة تطوير)`;
    const latest = s.latest;
    fill(card,
      h('h2', {}, 'التحديث'),
      h('div', {}, 'النسخة الحالية: ', h('b', { class: 'num' }, cur)),
      !s.installed ? h('div', { class: 'small muted' }, 'التحديث بيشتغل بس لما البرنامج يتفتح من "Start Sheet Metal.bat".') : null,
      s.check_error ? h('div', { class: 'small muted' }, 'آخر محاولة للتشييك على التحديثات مقدرتش توصل للنت.') : null,
      s.available
        ? h('div', { class: 'issue yellow', style: 'display:block' },
          h('b', {}, `في نسخة جديدة: ${latest.version} (رقم ${latest.build})`),
          latest.notes ? h('div', { class: 'small', style: 'white-space:pre-wrap;margin-top:4px' }, latest.notes) : null)
        : s.checked_at ? h('div', { class: 'small muted' }, `إنت على آخر نسخة (آخر تشييك ${fmtTime(s.checked_at)})`) : null,
      h('div', { class: 'row' },
        h('button', { class: 'btn', disabled: !s.installed, onclick: async (e) => {
          e.target.disabled = true;
          try { render(await post('/api/update/check')); } catch (ex) { toast(ex.message, true); e.target.disabled = false; }
        } }, 'شوف لو في تحديث'),
        s.available ? h('button', { class: 'btn primary', disabled: !s.installed || s.busy, onclick: (e) => apply(e.target, latest) }, 'تحديث') : null,
        s.can_rollback ? h('button', { class: 'btn danger', onclick: () => rollback(s) }, 'رجوع للنسخة السابقة') : null),
    );
  }
  async function apply(btn, latest) {
    const ok = await confirmModal('تحديث البرنامج',
      `هعمل نسخة احتياطية، وأحمّل النسخة ${latest.version} (رقم ${latest.build})، وأعيد تشغيل البرنامج. البرنامج هيقف دقيقة تقريباً. نكمل؟`, 'حدّث');
    if (!ok) return;
    btn.disabled = true;
    btn.textContent = 'جاري التحميل…';
    try {
      const r = await post('/api/update/apply');
      await waitForRestart(`اتحدث لنسخة ${r.version} ✓`);
    } catch (ex) {
      toast(ex.message, true);
      btn.disabled = false;
      btn.textContent = 'تحديث';
    }
  }
  async function rollback(s) {
    const text = s.rollback_loses_data
      ? 'التحديث الأخير غيّر شكل البيانات، فالرجوع هيرجّع البيانات كمان لوقت التحديث: أي شغل اتسجل من بعد التحديث هيختفي من البرنامج (بس هيتحفظ في نسخة احتياطية). متأكد؟'
      : 'البرنامج هيرجع للنسخة اللي كانت قبل آخر تحديث وهيعيد التشغيل. بياناتك مش هتتغير. نكمل؟';
    if (!(await confirmModal('رجوع للنسخة السابقة', text, 'ارجع'))) return;
    try {
      await post('/api/update/rollback', { confirm: true });
      await waitForRestart('رجعنا للنسخة السابقة ✓');
    } catch (ex) { toast(ex.message, true); }
  }
  render(await get('/api/update'));
  return card;
}

// Shows a full-screen notice until the app answers again, then reloads.
async function waitForRestart(doneMessage) {
  const box = h('div', { class: 'modal-back' }, h('div', { class: 'modal', style: 'text-align:center' },
    h('h2', {}, 'البرنامج بيعيد التشغيل…'), h('p', { class: 'muted' }, 'متقفلش الشباك الأسود. الصفحة هتفتح لوحدها.')));
  document.body.append(box);
  await new Promise((r) => setTimeout(r, 2500));
  for (let i = 0; i < 120; i++) {
    try {
      const res = await fetch('/api/session', { cache: 'no-store' });
      if (res.ok) {
        sessionStorage.setItem('after-restart', doneMessage);
        location.reload();
        return;
      }
    } catch { /* still restarting */ }
    await new Promise((r) => setTimeout(r, 1500));
  }
  box.querySelector('p').textContent = 'البرنامج لسه مارجعش. بص على الشباك الأسود على الكمبيوتر.';
}

// ---------- start with Windows ----------
export async function autostartCard() {
  const s = await get('/api/autostart');
  if (!s.supported) return null;
  const box = h('input', { type: 'checkbox', checked: s.enabled, onchange: async (e) => {
    try { await put('/api/autostart', { enabled: e.target.checked }); toast('اتحفظ'); } catch (ex) { toast(ex.message, true); e.target.checked = !e.target.checked; }
  } });
  return h('div', { class: 'card' }, h('label', { class: 'row' }, box, 'البرنامج يشتغل لوحده لما الكمبيوتر يفتح'));
}

// ---------- مشاركة ----------
export async function renderShare(main) {
  const d = await get('/api/share');
  const t = d.tunnel;
  const copy = (url) => h('button', { class: 'btn sm', onclick: async () => {
    try { await navigator.clipboard.writeText(url); toast('اتنسخ'); } catch { toast('انسخه بإيدك', true); }
  } }, 'نسخ');
  const STATE = { on: 'شغال', starting: 'بيتصل…', downloading: 'بيجهز اللينك لأول مرة…', error: 'فيه مشكلة', off: 'مقفول', missing: 'مقدرش يجهز اللينك' };

  const internet = h('div', { class: 'card grid share' },
    h('h2', {}, 'من أي مكان (إنترنت)'),
    h('div', {}, 'الحالة: ', h('span', { class: `pill ${t.state === 'on' ? 'green' : t.state === 'error' || t.state === 'missing' ? 'red' : 'yellow'}` }, STATE[t.state] || t.state)),
    t.url ? [
      svg(t.qr),
      h('div', { class: 'row' }, h('a', { href: t.url, target: '_blank', class: 'num', style: 'word-break:break-all' }, t.url), copy(t.url)),
      !t.fixed ? h('div', { class: 'small muted' }, 'اللينك ده بيتغير كل ما الكمبيوتر يعيد تشغيل — ارجع للصفحة دي تاخد الجديد.') : null,
    ] : null,
    t.state === 'missing' ? h('div', { class: 'small muted' }, 'اتأكد إن النت شغال ودوس "اتصل من جديد".') : null,
    t.error && t.state !== 'on' ? h('div', { class: 'small muted num' }, t.error) : null,
    h('div', { class: 'row' }, h('button', { class: 'btn', onclick: async () => {
      await post('/api/share/restart'); toast('بيتصل من جديد…'); setTimeout(() => renderShare(main), 6000);
    } }, 'اتصل من جديد'), h('button', { class: 'btn', onclick: () => renderShare(main) }, 'تحديث الصفحة')));

  const wifi = h('div', { class: 'card grid share' },
    h('h2', {}, 'على واي فاي الورشة'),
    d.lan.length === 0 ? h('div', { class: 'muted' }, 'الكمبيوتر مش متوصل بشبكة.') : d.lan.map((l) => [
      svg(l.qr), h('div', { class: 'row' }, h('span', { class: 'num' }, l.url), copy(l.url))]));

  const enabled = h('input', { type: 'checkbox', checked: d.settings.tunnel_enabled });
  const url = h('input', { value: d.settings.tunnel_url || '', placeholder: 'https://warsha.example.com', class: 'num' });
  const token = h('input', { type: 'password', placeholder: d.settings.tunnel_token_set ? '•••• (محفوظ — اكتب جديد لو عايز تغيره)' : 'Tunnel token', autocomplete: 'off' });
  const settings = h('div', { class: 'card grid' },
    h('h2', {}, 'إعدادات اللينك'),
    h('label', { class: 'row' }, enabled, 'افتح البرنامج على الإنترنت'),
    h('div', { class: 'small muted' }, 'لينك ثابت مش بيتغير: محتاج حساب Cloudflare مجاني ودومين. لو مش موجود سيب الخانتين فاضيين.'),
    h('div', { class: 'field' }, h('label', {}, 'اللينك الثابت'), url),
    h('div', { class: 'field' }, h('label', {}, 'Tunnel token'), token),
    h('div', { class: 'row' }, h('button', { class: 'btn primary', onclick: async () => {
      const body = { tunnel_enabled: enabled.checked, tunnel_url: url.value };
      if (token.value) body.tunnel_token = token.value;
      try { await put('/api/share/settings', body); toast('اتحفظ'); setTimeout(() => renderShare(main), 4000); } catch (ex) { toast(ex.message, true); }
    } }, 'حفظ'), d.settings.tunnel_token_set ? h('button', { class: 'btn', onclick: async () => {
      await put('/api/share/settings', { tunnel_token: '', tunnel_url: '' }); toast('رجعنا للينك المجاني'); renderShare(main);
    } }, 'امسح اللينك الثابت') : null));

  fill(main,
    h('div', { class: 'top' }, h('h1', {}, 'مشاركة'), h('span', { class: 'muted small' }, 'صوّر الكود بموبايلك عشان تفتح البرنامج')),
    h('div', { class: 'grid share-grid' }, internet, wifi),
    h('div', { style: 'margin-top:12px;max-width:560px' }, settings));
}
